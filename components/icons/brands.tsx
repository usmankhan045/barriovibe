/**
 * The platform logos, as filled marks on the same 24x24 grid the icon set uses.
 *
 * ## Why these are not in ./index.tsx
 *
 * That set is hand-drawn, stroked at 1.75, and its consistency is what makes
 * thirty-three icons read as one family. A brand mark is the opposite kind of
 * object: it is a FILLED glyph whose shape is not ours to harmonise, and a
 * stroked outline of somebody's logo is not their logo. So the two sets share a
 * grid and a `currentColor` contract and nothing else, and they are kept apart
 * so nobody is tempted to redraw one in the style of the other.
 *
 * ## Where the paths came from, and what is not here
 *
 * Simple Icons (simpleicons.org), whose path data is CC0. The marks themselves
 * are the trademarks of their owners and are used here for the one thing
 * trademark law calls nominative use: naming the platform the work runs on.
 * That is also the rule for adding to this file. A logo goes in when the site
 * says work happens on that platform, and never as decoration.
 *
 * Three entries in content/revenueEngine.ts have no mark here and are rendered
 * as words instead (see `PlatformMarks` in RevenueEngine):
 *
 *   Daraz                 no accurate source. A logo drawn from memory is a
 *                         worse misrepresentation than the name in type.
 *   Payments, Shipping    not platforms and not brands.
 *
 * ## Every mark is set to the same optical weight
 *
 * The `box` on each entry is a viewBox, and it is the one number in this file
 * that was measured rather than chosen. Rasterised at 96px and counted, the ink
 * in these nine marks spans 2,424 pixels (Amazon: a letter and a thin arc) to
 * 6,844 (LinkedIn: a filled tile). Set to one size they do not read as one row,
 * because a solid square at 16px is a much heavier object than an outline of
 * the same width, and the eye reads weight before it reads bounds.
 *
 * So each viewBox is grown by the fourth root of its ink against the set's
 * mean, which shrinks the mark inside a box that stays 18px for every one of
 * them. The fourth root and not the square root: normalising by area alone
 * sends LinkedIn to 0.75 and Amazon to 1.27, which is how you make a solid mark
 * look broken and a light one look inflated. A quarter of the way there is the
 * correction the eye asks for and no more.
 *
 * Only ever grown. A viewBox smaller than 0 0 24 24 magnifies the mark past the
 * edge of the `<svg>`, and an `<svg>` clips. That is why the scale is normalised
 * so the lightest mark is 1.0 and everything else comes down to meet it, and
 * why the call site asks for 18px rather than 16.
 *
 * Re-measure with the same method if a mark is added: draw it to a canvas at
 * 96px, count pixels with alpha, and put it through the same expression.
 *
 * ## Monochrome, and not only for taste
 *
 * These render in `currentColor` and the site colours them with its own ink. Brand colour was considered and dropped twice over: four saturated
 * marks per card would be the loudest thing in a section built out of white
 * glass, and their hex values cannot live in this repo anyway. Every colour on
 * this site resolves through app/tokens.css and scripts/check-tokens.mjs fails
 * the build on a raw hex, which is a rule worth more than a coloured logo.
 */

