export type BrandMarkName = keyof typeof MARKS;

export function hasBrandMark(platform: string): boolean {
  return platform.toLowerCase() in MARKS;
}

/**
 * One mark. Decorative by default: every caller renders the platform's name
 * beside it or in visually hidden text, so the accessible reading of a card is
 * the same list of words it always was.
 */
export function BrandMark({
  platform,
  size = 16,
  className,
}: {
  platform: string;
  size?: number;
  className?: string;
}): ReactNode {
  const mark = MARKS[platform.toLowerCase()];
  if (!mark) return null;

  return (
    <svg
      width={size}
      height={size}
      viewBox={mark.box}
      fill="currentColor"
      className={className}
      aria-hidden="true"
      focusable="false"
    >
      <path d={mark.path} />
    </svg>
  );
}
